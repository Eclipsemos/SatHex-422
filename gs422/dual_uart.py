"""X26 UART6 control / UART8 RX-only transport for an explicit Revised runtime.

Owns only serial descriptors; caller owns runtime workers/telemetry producers and
shutdown. No install/start side effects, no fabricated telemetry defaults.
"""
import os
import select
import time
from .platform import Serial


class DualUART:
    def __init__(self, runtime, control_port='/dev/ttyS6', upload_port='/dev/ttyS8',
                 baud=115200, *, max_pending=65536, tx_timeout=3, clock=time.monotonic):
        if max_pending < 512 or tx_timeout <= 0:
            raise ValueError('invalid output bounds')
        if os.path.samefile(control_port, upload_port):
            raise ValueError('control and upload must be different UART devices')
        self.runtime, self.clock = runtime, clock
        self.max_pending, self.tx_timeout = max_pending, tx_timeout
        self.pending = bytearray()
        self.last_progress = None
        self.control = self.upload = None
        try:
            self.control = Serial(control_port, baud, 'N', 1)
            self.upload = Serial(upload_port, baud, 'N', 1, receive_only=True)
        except BaseException:
            self.close()
            raise

    def _queue(self, data):
        if len(self.pending) + len(data) > self.max_pending:
            raise BufferError('control UART output queue limit')
        if data and not self.pending:
            self.last_progress = self.clock()
        self.pending.extend(data)

    def pump(self, timeout=.001):
        if self.control is None or self.upload is None:
            raise RuntimeError('transport is closed')
        if self.runtime.failure:
            raise RuntimeError('runtime worker failed: ' + self.runtime.failure)
        if self.runtime.stop.is_set():
            raise RuntimeError('runtime has stopped')
        self._queue(self.runtime.drain_replies())
        control_fd, upload_fd = self.control.fd, self.upload.fd
        reads, writes, _ = select.select([control_fd, upload_fd],
                                        [control_fd] if self.pending else [], [], timeout)
        # A single bounded read per channel prevents upload traffic starving control.
        for fd in (control_fd, upload_fd):
            data = b''
            if fd in reads:
                try:
                    data = os.read(fd, 4096)
                except BlockingIOError:
                    continue
                if not data:
                    raise OSError('UART disconnected')
            if fd == control_fd:
                self._queue(self.runtime.feed_control(data))
            elif self.runtime.feed_upload(data):
                raise RuntimeError('RX-only channel attempted a response')
        if self.pending:
            # Include responses generated by this cycle without waiting a second poll.
            if control_fd in writes or select.select([], [control_fd], [], 0)[1]:
                try:
                    written = os.write(control_fd, self.pending)
                    if written == 0:
                        raise OSError('UART write zero')
                    del self.pending[:written]
                    self.last_progress = self.clock()
                except BlockingIOError:
                    pass
            if self.pending and self.clock() - self.last_progress >= self.tx_timeout:
                raise TimeoutError('control UART output stalled')
        if self.runtime.failure:
            raise RuntimeError('runtime worker failed: ' + self.runtime.failure)

    def close(self):
        try:
            if self.upload is not None:
                self.upload.close()
        finally:
            self.upload = None
            if self.control is not None:
                self.control.close()
            self.control = None

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()
